CREATE DATABASE IF NOT EXISTS `__DATABASE_NAME__` CHARSET utf8mb4;

USE `__DATABASE_NAME__`;

CREATE TABLE IF NOT EXISTS category(
id_category INT PRIMARY KEY AUTO_INCREMENT NOT NULL,
category_name VARCHAR(50) UNIQUE NOT NULL
);

CREATE TABLE IF NOT EXISTS book(
id_book INT PRIMARY KEY AUTO_INCREMENT NOT NULL,
title VARCHAR(50) NOT NULL,
content VARCHAR(255) NOT NULL,
publish_at DATETIME NOT NULL,
author VARCHAR(100) NOT NULL,
cover VARCHAR(255),
created_at DATETIME DEFAULT CURRENT_TIMESTAMP NOT NULL,
updated_at DATETIME
);

CREATE TABLE IF NOT EXISTS `user`(
id_user INT PRIMARY KEY AUTO_INCREMENT NOT NULL,
firstname VARCHAR(50) NOT NULL,
lastname VARCHAR(50) NOT NULL,
email VARCHAR(50) UNIQUE NOT NULL,
hash_password VARCHAR(100) NOT NULL,
created_at DATETIME DEFAULT CURRENT_TIMESTAMP NOT NULL,
updated_at DATETIME,
img_profil VARCHAR(200),
`grant` VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS lending(
id_lending INT PRIMARY KEY AUTO_INCREMENT NOT NULL,
lending_at DATETIME DEFAULT CURRENT_TIMESTAMP NOT NULL,
`status` BOOL NOT NULL,
user_id INT NOT NULL,
book_id INT NOT NULL,
CONSTRAINT fk_lend_user
FOREIGN KEY(user_id)
REFERENCES `user`(id_user)
ON DELETE CASCADE,
CONSTRAINT fk_link_book
FOREIGN KEY(book_id)
REFERENCES book(id_book)
ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS book_category(
id_book INT,
id_category INT,
PRIMARY KEY(id_book, id_category),
CONSTRAINT fk_completed_book
FOREIGN KEY(id_book)
REFERENCES book(id_book),
CONSTRAINT fk_completed_category
FOREIGN KEY(id_category)
REFERENCES category(id_category)
);